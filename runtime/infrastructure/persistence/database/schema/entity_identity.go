package schema

import (
	"strings"

	ormschema "github.com/domainry/domainry-orm/schema"
)

// physicalAutoIncrementID returns the final id definition used directly by
// Runtime's legacy string-assembled schema declarations.
func physicalAutoIncrementID(driver string) string {
	switch strings.ToLower(strings.TrimSpace(driver)) {
	case "mysql":
		return "id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY"
	case "postgres", "postgresql":
		return "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	default:
		return "id INTEGER PRIMARY KEY AUTOINCREMENT"
	}
}

func physicalIDColumn() ormschema.ColumnDefinition {
	return ormschema.Column("id", ormschema.BigInt()).NotNull().AutoIncrement()
}
